#Examples of logical operators in Python

number1 = 10
number2 = 20

and_result = (number1 < number2) and (number1 != number2)
or_result = (number1 > number2) or (number1 == number2)
not_result = not (number1 < number2)

print("AND Result:", and_result)
print("OR Result:", or_result)
print("NOT Result:", not_result)


